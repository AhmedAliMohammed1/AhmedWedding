import { expect, test } from '@playwright/test';
test('Arabic invitation navigation, countdown, photos and guest notes', async ({page}) => {
 await page.route('**/api/notes**',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({notes:[],pagination:{page:1,pageSize:6,total:0,totalPages:1,hasPreviousPage:false,hasNextPage:false}})}));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/');
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await expect(page.getByRole('heading',{name:'احمد و الاء',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'اكتشفوا دعوتنا'}).click();
 await expect(page.locator('#details')).toBeInViewport();
 await expect(page.locator('.countdown-cell')).toHaveCount(4);
 await page.getByRole('button',{name:'تكبير الصورة: جمع الله بين قلبينا'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'الصورة التالية'}).click();
 await expect(page.getByRole('dialog').getByText('ومعك تحلو كل البدايات')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('link',{name:'الطريق إلى فرحتنا'})).toHaveAttribute('href',/30.6357971%2C31.5591093/);
 await page.getByRole('button',{name:'عرض كل التهاني'}).click();
 await expect(page.getByText('لا توجد تهانٍ بعد، كن أول من يشاركنا المحبة.')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
});
